/**
 * 특정 서비스의 지역 키워드 조합 생성
 * @example makeRegionalKeywords("의자 천갈이", "의자 가죽 교체")
 * → ["인천 의자 천갈이", "인천 의자 가죽 교체", "청라 의자 천갈이", ...]
 */
export function makeRegionalKeywords(...services: string[]): string[] {
  return REGIONS.flatMap((region) =>
    services.map((service) => `${region} ${service}`),
  );
}
